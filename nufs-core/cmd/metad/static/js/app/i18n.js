  // ---- reactive locale + translation ----
  var KEY = 'nufs.locale';
  function storedLocale() {
    try {
      var v = localStorage.getItem(KEY);
      return (v === 'zh' || v === 'en') ? v : 'zh';
    } catch (e) { return 'zh'; }
  }
  I.locale = Vue.ref(storedLocale());
  I.current = function () { return I.locale.value; };

  function interpolate(msg, params) {
    if (!params) return msg;
    return msg.replace(/\{(\w+)\}/g, function (m, k) {
      var v = params[k];
      return v == null ? m : String(v);
    });
  }
  I.t = function (key, params) {
    var loc = I.locale.value;
    var cur = (DICT[loc] && DICT[loc][key]);
    if (cur != null) return interpolate(cur, params);
    var en = (DICT.en && DICT.en[key]);
    if (en != null) return interpolate(en, params);
    return key;
  };

  // _n(key, n): pick a pluralized form. Define DICT[loc][key] and
  // DICT[loc][key + '._plur'] for English singular/plural; Chinese defines
  // only [key] (with {n} baked in or used for both). Falls back to t().
  I._n = function (key, n) {
    var loc = I.locale.value;
    var d = DICT[loc] || {};
    var k = (n === 1) ? key : key + '._plur';
    if (d[k] != null) return interpolate(d[k], { n: n });
    return I.t(key, { n: n });
  };

  I.setLocale = function (l) {
    if (l !== 'zh' && l !== 'en') return;
    I.locale.value = l;
    try { localStorage.setItem(KEY, l); } catch (e) {}
    if (document && document.documentElement) { document.documentElement.lang = (l === 'zh' ? 'zh-CN' : 'en'); }
  };

  // Apply the persisted language to <html lang> on boot (so the toggle state
  // and page announcements match even before the app renders).
  I.setLocale(I.current());
